from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from app.game.config import DEFAULT_RULES_CONFIG, RulesConfig

Color = Literal["white", "black"]
Rank = Literal["man", "king"]
GameStatus = Literal["waiting", "active", "finished"]
FinishReason = Literal["no_pieces", "no_legal_moves", "resignation"]
Coord = tuple[int, int]


def is_in_bounds(row: int, col: int, board_size: int = 8) -> bool:
    """Return True if (row, col) lies inside the board."""
    return 0 <= row < board_size and 0 <= col < board_size


def is_playable_square(row: int, col: int, board_size: int = 8) -> bool:
    """Return True if (row, col) is one of the 32 dark playable squares."""
    return is_in_bounds(row, col, board_size) and (row + col) % 2 == 1


def opponent_of(color: Color) -> Color:
    """Return the opposing player's color."""
    return "black" if color == "white" else "white"


def forward_row_delta(color: Color) -> int:
    """Return row step direction for men: white moves up (-1), black moves down (+1)."""
    return -1 if color == "white" else 1


def promotion_row(color: Color, board_size: int = 8) -> int:
    """Return the far row index where a man promotes to a king/Dama."""
    return 0 if color == "white" else board_size - 1


class Piece(BaseModel):
    """Single game piece on the board."""

    model_config = ConfigDict(frozen=True)

    id: str
    color: Color
    rank: Rank = "man"


class MoveAttempt(BaseModel):
    """Complete turn submitted by a player."""

    model_config = ConfigDict(frozen=True, populate_by_name=True)

    from_pos: Coord = Field(alias="from", serialization_alias="from")
    landings: list[Coord]


class LegalMove(BaseModel):
    """Complete legal turn generated by the rules engine."""

    model_config = ConfigDict(frozen=True, populate_by_name=True)

    from_pos: Coord = Field(alias="from", serialization_alias="from")
    landings: list[Coord]
    captured: list[Coord] = Field(default_factory=list)
    is_capture: bool = False


class LastMoveInfo(BaseModel):
    """Metadata describing the most recently committed turn for UI highlighting."""

    model_config = ConfigDict(frozen=True, populate_by_name=True)

    by: Color
    piece_id: str
    from_pos: Coord = Field(alias="from", serialization_alias="from")
    landings: list[Coord]
    captured: list[Coord] = Field(default_factory=list)
    promoted: bool = False


class GameState(BaseModel):
    """Authoritative game state snapshot.

    Note on `captured`: maps each color to the number of pieces *of that color*
    that have been captured and removed from the board (so for a standard 12-piece
    match, `pieces_on_board[color] + captured[color] == 12`).
    """

    model_config = ConfigDict(populate_by_name=True)

    board: list[list[Piece | None]]
    current_turn: Color = "white"
    status: GameStatus = "waiting"
    winner: Color | None = None
    finish_reason: FinishReason | None = None
    captured: dict[Color, int] = Field(default_factory=lambda: {"white": 0, "black": 0})
    move_number: int = 0
    revision: int = 0
    last_move: LastMoveInfo | None = None
    rules_config: RulesConfig = Field(default_factory=lambda: DEFAULT_RULES_CONFIG)
    legal_moves: list[LegalMove] = Field(default_factory=list)
    mandatory_capture: bool = False
